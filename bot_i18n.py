def _parse_body_to_visual_items(body_text: str, sec_idx: int) -> list:
    """Converte o texto localizado do guia em itens visuais estruturados (badge, descricao, destaque)."""
    import re
    items = []
    raw_lines = [ln.strip() for ln in body_text.split("\n") if ln.strip()]
    step_num = 1
    for ln in raw_lines:
        # Remove emojis compostos/quebrados no inicio
        ln_clean = re.sub(r"^[\u20e3\ufe0f1-9•🟢🔥💻🎮🎯📺💡🪟⚡🥚🏛🧭🏆🛡🔌⭐👁\s]+", "", ln).strip()
        if not ln_clean:
            continue
        if ":" in ln_clean and len(ln_clean.split(":", 1)[0]) <= 36:
            left, right = ln_clean.split(":", 1)
            badge = f"[{left.strip()[:16]}]"
            desc = right.strip() or left.strip()
            is_hi = sec_idx in (1, 2) or any(k in left for k in ("[E]", "[Z]", "[C]", "Altar", "1", "2"))
            items.append((badge, desc, is_hi))
        else:
            badge = f"[#{step_num}]" if sec_idx == 1 else f"[INFO {step_num}]"
            items.append((badge, ln_clean, step_num <= 2))
            step_num += 1
    return items


